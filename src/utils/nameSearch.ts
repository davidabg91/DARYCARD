// Търсене по име, което не се спъва в интервалите.
//
// В базата има имена с два интервала между думите („КАЛОЯН  ПЕТКОВ“ — 48 такива)
// и с интервал в края (566). Браузърът ги рисува с един интервал, затова на
// екрана изглеждат наред, а търсенето на „КАЛОЯН ПЕТКОВ“ не ги намираше: то
// сравняваше буква по буква, с интервалите.

/** Малки букви, един интервал между думите, без интервали в краищата. */
export const searchText = (s: string | null | undefined): string =>
    String(s || '').toLowerCase().replace(/\s+/g, ' ').trim();

/**
 * Съдържа ли името всяка дума от търсеното. `term` е вече минал през searchText.
 * По думи, а не като цял низ — така „КАЛОЯН ПЕТКОВ“ намира и „КАЛОЯН ИВАНОВ
 * ПЕТКОВ“, и „ПЕТКОВ КАЛОЯН“.
 */
export const nameMatches = (name: string | null | undefined, term: string): boolean => {
    const n = searchText(name);
    return term.split(' ').every(word => n.includes(word));
};
